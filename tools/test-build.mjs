#!/usr/bin/env node
// Build regressions: Node 18+, no browser or external dependencies.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const tempRoot = path.join(root, '.tmp');
fs.mkdirSync(tempRoot, { recursive: true });
const temp = fs.mkdtempSync(path.join(tempRoot, 'build-test-'));
const read = p => fs.readFileSync(path.join(temp, p), 'utf8');
const write = (p, text) => {
  fs.mkdirSync(path.dirname(path.join(temp, p)), { recursive: true });
  fs.writeFileSync(path.join(temp, p), text);
};
const hashes = () => {
  const result = {};
  const walk = dir => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const file = path.join(dir, entry.name);
      if (entry.isDirectory()) walk(file);
      else result[path.relative(temp, file)] = createHash('sha256').update(fs.readFileSync(file)).digest('hex');
    }
  };
  walk(temp);
  return result;
};
const run = (args = [], status = 0, message) => {
  const before = hashes();
  const r = spawnSync(process.execPath, [path.join(temp, 'build.mjs'), '--root', temp, ...args], {
    encoding: 'utf8', timeout: 30000,
  });
  assert.equal(r.status, status, r.stderr || String(r.error));
  if (message) assert.match(r.stderr, message);
  if (args.includes('--check')) assert.deepEqual(hashes(), before, '--check must not write files');
};

try {
  const sources = ['packs/motion/pack.js', 'packs/motion/meta.json'];
  for (const p of sources) write(p, fs.readFileSync(path.join(root, p), 'utf8').replace(/\r\n/g, '\n'));
  write('build.mjs', fs.readFileSync(path.join(root, 'tools/build.mjs'), 'utf8').replace(/\r\n/g, '\n'));
  run();
  run(['--check']);
  const lfBuild = hashes();
  const lfVersion = JSON.parse(read('api/v1/catalog.json')).version;

  // Convert both pack sources and the builder; function.toString() must not leak CRLF into the output.
  for (const p of [...sources, 'build.mjs']) write(p, read(p).replace(/\r?\n/g, '\r\n'));
  run(['--check']);
  run();
  const crlfBuild = hashes();
  for (const p of Object.keys(lfBuild).filter(p => ![...sources, 'build.mjs'].includes(p.split(path.sep).join('/')))) {
    assert.equal(crlfBuild[p], lfBuild[p], 'line endings changed generated bytes: ' + p);
  }
  assert.equal(JSON.parse(read('api/v1/catalog.json')).version, lfVersion);

  // A legitimate CRLF Git checkout of generated text is current, but content drift is not.
  const prompt = read('api/v1/ko/p/001.txt');
  write('api/v1/ko/p/001.txt', prompt.replace(/\r?\n/g, '\r\n'));
  run(['--check']);
  write('api/v1/ko/p/001.txt', prompt + 'stale content\n');
  run(['--check'], 1, /api\/v1\/ko\/p\/001\.txt: generated file is stale/);
  write('api/v1/ko/p/001.txt', prompt);

  const readme = read('packs/motion/README.ko.md');
  fs.unlinkSync(path.join(temp, 'packs/motion/README.ko.md'));
  run(['--check'], 1, /README\.ko\.md: generated file is missing/);
  write('packs/motion/README.ko.md', readme);
  write('api/v1/ko/p/999.txt', 'obsolete ID\n');
  run(['--check'], 1, /999\.txt: unexpected generated file/);
  run(); // A build removes obsolete API files.
  run(['--check']);

  const meta = JSON.parse(read('packs/motion/meta.json'));
  meta.elements[0].meaning.ko += ' 테스트';
  write('packs/motion/meta.json', JSON.stringify(meta, null, 2) + '\n');
  run(['--check'], 1, /generated file is stale/);
  run();
  assert.notEqual(JSON.parse(read('api/v1/catalog.json')).version, lfVersion, 'content changes must invalidate the cache');
  run(['--check']);
  console.log('Build tests passed: LF/CRLF byte parity, missing/stale/extra outputs, source changes, cache invalidation and read-only checks.');
} finally {
  assert.equal(path.dirname(path.resolve(temp)), path.resolve(tempRoot));
  assert.ok(path.basename(temp).startsWith('build-test-'));
  fs.rmSync(temp, { recursive: true, force: true });
}
